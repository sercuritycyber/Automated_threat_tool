const DOCS = { privacy: PRIVACY, terms: TERMS, cookies: COOKIES };
const TITLES = { privacy: "Privacy Policy", terms: "Terms of Service", cookies: "Cookies" };

export function legalHtml(cfg, name) {
  const src = DOCS[name];
  if (!src) return null;
  const filled = src
    .replaceAll("{{brand}}", cfg.brand)
    .replaceAll("{{legal_name}}", cfg.company_legal_name || "SecurityCyber")
    .replaceAll("{{ico}}", cfg.ico_reg || (cfg.ico_pending ? "(registration in progress)" : "(registration pending)"))
    .replaceAll("{{contact}}", cfg.contact_email || "securitycyber_cti@securitycyber.uk")
    .replaceAll("{{site}}", cfg.site_url)
    .replaceAll("{{terms_version}}", cfg.terms_version)
    .replaceAll("{{ret_cancel}}", String(cfg.retention_days_cancelled))
    .replaceAll("{{ret_unconf}}", String(cfg.retention_days_unconfirmed));
  return { title: TITLES[name], html: mdToHtml(filled) };
}
